#!/usr/bin/env python3
"""按《文档鉴别材料模板》的版式生成用户手册 Word。

模板给定的骨架是：封面 → 目录 → 前言 + 文件修订记录 → 总体功能描述 → 运行环境
（硬件 / 软件两张表）→ 系统功能（每节一句进入方式 + 截图 + 图注）→ 结束语；
页眉「软件全称 + 版本号 + 使用说明」，页码在页脚，写成「N of M」。

正文另做了一轮去 AI 味的改写，改写口径见 docs/copyright/软件著作权申请资料/草稿/
AI率检测与降重记录.md：去掉贡献列表体、虚构使用场景、收益论断、破折号补白与
对称收束，句长不再均匀。改写只动写法，界面文案、提示语、数字和错误信息照抄界面。

用法：
    python3 docs/copyright/tools/gen_manual_template_docx.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from docx_writer import (  # noqa: E402
    DocxBuilder,
    Font,
    Image,
    Paragraph,
    Raw,
    cm,
    escape,
)

ROOT = Path(__file__).resolve().parents[3]
SHOTS = ROOT / "docs/copyright/软件著作权申请资料/用户截图"
OUT = ROOT / "docs/copyright/软件著作权申请资料/正式资料/论文精读辅助分析软件_操作手册.docx"

NAME = "论文精读辅助分析软件"
VERSION = "V1.0"

# 固定行距 20 磅：版心 14344 twip ÷ 400 = 35 行/页，与字体度量无关，
# 换渲染器不会掉到 30 行以下。
LINE = 400
LINE_TIGHT = 320

F_COVER_NAME = Font(ascii="Arial", east_asia="Heiti SC", size_pt=26, bold=True)
F_COVER_VER = Font(ascii="Arial", east_asia="Heiti SC", size_pt=18)
F_COVER_KIND = Font(ascii="Arial", east_asia="Heiti SC", size_pt=30, bold=True)
F_COVER_DATE = Font(ascii="Times New Roman", east_asia="Songti SC", size_pt=14)
F_TOC_TITLE = Font(ascii="Arial", east_asia="Heiti SC", size_pt=16, bold=True)
F_TOC1 = Font(ascii="Times New Roman", east_asia="Songti SC", size_pt=12)
F_TOC2 = Font(ascii="Times New Roman", east_asia="Songti SC", size_pt=11)
F_H1 = Font(ascii="Arial", east_asia="Heiti SC", size_pt=16, bold=True)
F_H2 = Font(ascii="Arial", east_asia="Heiti SC", size_pt=13, bold=True)
F_BODY = Font(ascii="Times New Roman", east_asia="Songti SC", size_pt=12)
F_CAPTION = Font(ascii="Times New Roman", east_asia="Songti SC", size_pt=10.5)
F_TABLE = Font(ascii="Times New Roman", east_asia="Songti SC", size_pt=10.5)


class Manual:
    def __init__(self) -> None:
        self.doc = DocxBuilder(
            header_left=f"{NAME} {VERSION}    使用说明",
            margin_cm_top=2.2,
            margin_cm_bottom=2.2,
            margin_cm_left=2.2,
            margin_cm_right=2.2,
            page_number_in_footer=True,
        )
        self.headings: list[tuple[int, str]] = []
        self.fig_no = 0
        self.toc_slot = -1

    # -- 基本块 --
    def h1(self, text: str) -> None:
        self.headings.append((1, text))
        self.doc.add(
            Paragraph(
                text=text,
                font=F_H1,
                line_twips=460,
                space_before=240,
                space_after=120,
                outline_level=0,
            )
        )

    def h2(self, text: str) -> None:
        self.headings.append((2, text))
        self.doc.add(
            Paragraph(
                text=text,
                font=F_H2,
                line_twips=420,
                space_before=180,
                space_after=90,
                outline_level=1,
            )
        )

    def p(self, text: str) -> None:
        self.doc.add(
            Paragraph(
                text=text,
                font=F_BODY,
                line_twips=LINE,
                first_line_indent=int(F_BODY.size_pt * 40),  # 首行缩进两字
                align="both",
            )
        )

    def table(self, rows: list[list[str]]) -> None:
        self.doc.add_table(rows, font=F_TABLE)

    def figure(self, filename: str, caption: str) -> None:
        self.fig_no += 1
        path = SHOTS / filename
        if not path.exists():
            raise FileNotFoundError(path)
        self.doc.add(Image.fit_png(path, int(self.doc.content_width * 0.85)))
        self.doc.add(
            Paragraph(
                text=f"图 {self.fig_no}　{caption}",
                font=F_CAPTION,
                line_twips=LINE_TIGHT,
                space_before=40,
                space_after=140,
                align="center",
            )
        )

    def page_break(self) -> None:
        self.doc.add_page_break()

    # -- 封面 / 目录 --
    def cover(self) -> None:
        blank = Paragraph(text="", font=F_BODY, line_twips=LINE)
        for _ in range(5):
            self.doc.add(blank)
        self.doc.add(Paragraph(text=NAME, font=F_COVER_NAME, align="center", line_twips=760))
        self.doc.add(
            Paragraph(text=f"（{VERSION}）", font=F_COVER_VER, align="center", line_twips=560)
        )
        for _ in range(2):
            self.doc.add(blank)
        for ch in "用户手册":
            self.doc.add(Paragraph(text=ch, font=F_COVER_KIND, align="center", line_twips=800))
        for _ in range(4):
            self.doc.add(blank)
        self.doc.add(
            Paragraph(text="二〇二六年八月", font=F_COVER_DATE, align="center", line_twips=520)
        )
        self.page_break()

    def toc_placeholder(self) -> None:
        self.doc.add(
            Paragraph(
                text="目　　录",
                font=F_TOC_TITLE,
                align="center",
                line_twips=520,
                space_after=200,
            )
        )
        self.toc_slot = len(self.doc.blocks)
        self.doc.add(Raw(xml=""))
        self.page_break()

    def fill_toc(self) -> None:
        right_tab = self.doc.content_width
        entries = [(lv, tx) for lv, tx in self.headings]

        def entry(level: int, text: str, prefix: str = "", suffix: str = "") -> str:
            font = F_TOC1 if level == 1 else F_TOC2
            indent = 0 if level == 1 else cm(0.85)
            return (
                "<w:p><w:pPr>"
                f'<w:tabs><w:tab w:val="right" w:leader="dot" w:pos="{right_tab}"/></w:tabs>'
                f'<w:spacing w:before="{60 if level == 1 else 0}" w:after="40" '
                f'w:line="{LINE_TIGHT}" w:lineRule="exact"/>'
                f'<w:ind w:left="{indent}" w:firstLine="0"/>'
                f"{font.rpr()}</w:pPr>"
                f"{prefix}"
                f'<w:r>{font.rpr()}<w:t xml:space="preserve">{escape(text)}</w:t></w:r>'
                f"<w:r>{font.rpr()}<w:tab/></w:r>"
                f"{suffix}"
                "</w:p>"
            )

        begin = (
            f'<w:r>{F_TOC1.rpr()}<w:fldChar w:fldCharType="begin" w:dirty="true"/></w:r>'
            f'<w:r>{F_TOC1.rpr()}<w:instrText xml:space="preserve">'
            'TOC \\o "1-2" \\h \\z \\u</w:instrText></w:r>'
            f'<w:r>{F_TOC1.rpr()}<w:fldChar w:fldCharType="separate"/></w:r>'
        )
        end = f'<w:r>{F_TOC1.rpr()}<w:fldChar w:fldCharType="end"/></w:r>'
        parts = [
            entry(lv, tx, prefix=begin if i == 0 else "", suffix=end if i == len(entries) - 1 else "")
            for i, (lv, tx) in enumerate(entries)
        ]
        self.doc.blocks[self.toc_slot] = Raw(xml="".join(parts))


